#!/usr/bin/env python3
"""Generate the Arabic/Urdu joining-forms table used by src/arabic_shape.cpp.
Reads the Unicode data bundled with Python (presentation forms and their compatibility mappings).
Usage: python tools/gen_arabic_table.py > src/arabic_forms.inc"""
import unicodedata

forms = {}  # base -> {tag: cp}
lig = {}    # (a, b) -> {tag: cp}
for cp in list(range(0xFB50, 0xFE00)) + list(range(0xFE70, 0xFEFD)):
    d = unicodedata.decomposition(chr(cp))
    if not d.startswith("<"):
        continue
    tag, rest = d.split(" ", 1)[0], d.split(" ", 1)[1].split()
    tag = tag.strip("<>")
    if tag not in ("isolated", "final", "initial", "medial"):
        continue
    base = [int(x, 16) for x in rest]
    if len(base) == 1:
        forms.setdefault(base[0], {})[tag] = cp
    elif len(base) == 2 and base[0] == 0x0644 and base[1] in (0x0622, 0x0623, 0x0625, 0x0627):
        lig.setdefault((base[0], base[1]), {})[tag] = cp

print("// GENERATED by tools/gen_arabic_table.py from Python's Unicode data. Do not edit.")
print("// base, isolated, final, initial, medial (0 = this form does not exist)")
print("static const ArForm AR_FORMS[] = {")
for base in sorted(forms):
    f = forms[base]
    print("  {0x%04X, 0x%04X, 0x%04X, 0x%04X, 0x%04X}," % (base, f.get("isolated", 0), f.get("final", 0), f.get("initial", 0), f.get("medial", 0)))
print("};")
print("static const ArLig AR_LIGS[] = {")
for (a, b) in sorted(lig):
    f = lig[(a, b)]
    print("  {0x%04X, 0x%04X, 0x%04X}," % (b, f.get("isolated", 0), f.get("final", 0)))
print("};")
